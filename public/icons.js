  function icon(name, size = 20) {
    const body = PATHS[name] || "";
    return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
  }

  // Thay mọi <i data-icon="x" data-size="16"> trong root bằng SVG.
  function hydrate(root = document) {
    root.querySelectorAll("i[data-icon]").forEach((node) => {
      const wrapper = document.createElement("span");
      wrapper.innerHTML = icon(node.dataset.icon, Number(node.dataset.size) || 20);
      node.replaceWith(wrapper.firstChild);
    });
  }

  function esc(value) {
    return String(value ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#39;");
  }

  // Chữ cái đầu của tên gọi (từ cuối) như "Nguyễn Văn Bảo" -> "B".
  function initial(name) {
    const words = String(name || "?").trim().split(/\s+/);
    return (words[words.length - 1] || "?").charAt(0) || "?";
  }

  function tone(name) {
    let hash = 0;
    for (const ch of String(name || "")) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
    return hash % 5;
  }

  function avatar(name, size = "md") {
    return `<span class="avatar avatar-${size} avatar-tone-${tone(name)}">${esc(initial(name))}</span>`;
  }

  window.UI = { icon, hydrate, esc, initial, tone, avatar };
